def get_ethiopian_time():
    now = datetime.now()
    hour = now.hour
    minute = now.minute
    second = now.second
    date_str = now.strftime("%Y-%m-%d")
    if 6 <= hour < 18:
        eth_hour = hour - 6
        if eth_hour == 0: eth_hour = 12
        period = "ጠዋት" if hour < 12 else "ከሰዓት"
    else:
        eth_hour = hour - 18 if hour >= 18 else hour + 6
        if eth_hour == 0: eth_hour = 12
        period = "ማታ"
    return f"{date_str} {eth_hour}:{minute:02d}:{second:02d} {period}"

